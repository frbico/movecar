import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {DatabaseSync} from 'node:sqlite';
import http from 'node:http';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import WebSocket from 'ws';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const listen=s=>new Promise(r=>s.listen(0,'127.0.0.1',r));
const close=s=>new Promise(r=>s.close(r));

test('pairing, native delivery, history, photo, confirmation and revocation',async()=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'movecar-app-'));
  const probe=http.createServer();await listen(probe);const port=probe.address().port;await close(probe);
  const origin=`http://127.0.0.1:${port}`;
  const env={...process.env,NODE_ENV:'test',PORT:String(port),DB_PATH:path.join(dir,'state.sqlite'),SOURCE_PATH:path.join(root,'tests/fake-worker.js')};
  let stderr='';
  const server=spawn(process.execPath,['server.mjs'],{cwd:root,env,stdio:'pipe'});
  server.stderr.on('data',d=>stderr+=d);
  const call=(route,body,headers={})=>fetch(origin+route,{method:'POST',headers:{'Content-Type':'application/json',...headers},body:JSON.stringify(body)});
  try{
    let ready=false;for(let n=0;n<100;n++){try{if((await fetch(origin+'/healthz')).ok){ready=true;break}}catch{}await sleep(40)}assert.ok(ready,stderr);
    const password=fs.readFileSync(path.join(dir,'admin-initial-password'),'utf8').trim();
    const login=await call('/api/admin/login',{password});assert.equal(login.status,200);
    const cookie=login.headers.get('set-cookie').split(';')[0];
    const csrf=(await (await fetch(origin+'/api/admin/session',{headers:{Cookie:cookie}})).json()).csrf;
    const admin=(route,body)=>call(route,body,{Cookie:cookie,Origin:origin,'X-CSRF-Token':csrf});
    const pairing=async()=>{const r=await admin('/api/admin/app-pairing',{});assert.equal(r.status,200,await r.clone().text());const j=await r.json();assert.match(j.qrDataUrl,/^data:image\/svg\+xml;base64,/);return new URL(j.pairingUri).searchParams.get('code')};
    const firstCode=await pairing();
    const x=await call('/api/app/pair',{code:firstCode,platform:'xiaomi',name:'Redmi K70'});assert.equal(x.status,200);const xiaomi=await x.json();
    assert.equal((await call('/api/app/pair',{code:firstCode,platform:'samsung',name:'Other'})).status,410,'pairing code is one-use');
    const secondCode=await pairing();
    const s=await call('/api/app/pair',{code:secondCode,platform:'samsung',name:'Galaxy S24 Ultra'});assert.equal(s.status,200);const samsung=await s.json();
    const db=new DatabaseSync(path.join(dir,'state.sqlite'));
    const expiredCode=await pairing();db.prepare('UPDATE app_pairings SET expires_at=? WHERE digest=?').run(Date.now()-1,(await import('node:crypto')).createHash('sha256').update(expiredCode).digest('hex'));
    assert.equal((await call('/api/app/pair',{code:expiredCode,platform:'xiaomi',name:'Expired'})).status,410);
    db.close();
    const appHeaders={Authorization:`Bearer ${samsung.credential}`};
    const config=await admin('/api/admin/settings',{publicUrl:'',phoneNumber:'',rateLimitSeconds:0,barkEnabled:false,serverchanEnabled:false,sc3Enabled:false,appEnabled:true});assert.equal(config.status,200,await config.clone().text());
    const connect=credential=>new Promise((resolve,reject)=>{
      const ws=new WebSocket(origin.replace('http:','ws:')+'/api/app/events',{headers:{Authorization:`Bearer ${credential}`}});
      ws.once('open',()=>resolve(ws));ws.once('error',reject);
    });
    const xSocket=await connect(xiaomi.credential);let sSocket=await connect(samsung.credential);
    const next=(ws,type)=>new Promise((resolve,reject)=>{
      const timer=setTimeout(()=>reject(Error(`WebSocket ${type} event missing`)),2000);
      const handler=bytes=>{const event=JSON.parse(bytes.toString());if(event.type!==type)return;clearTimeout(timer);ws.off('message',handler);resolve(event)};
      ws.on('message',handler);
    });
    const xRequest=next(xSocket,'request'),sRequest=next(sSocket,'request');
    const request=await call('/api/notify',{message:'车辆挡住出口'});assert.equal(request.status,200,await request.clone().text());const item=await request.json();
    assert.equal(item.channels.app,'ok');assert.equal((await xRequest).id,item.requestId);assert.equal((await sRequest).id,item.requestId);
    const list=await fetch(origin+'/api/app/requests',{headers:appHeaders});assert.equal(list.status,200);assert.equal((await list.json()).items[0].message,'车辆挡住出口');
    const info=await fetch(origin+'/api/app/requests/'+item.requestId,{headers:appHeaders});assert.equal((await info.json()).status,'waiting');
    const png=Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),Buffer.alloc(32,1)]);
    const xPhoto=next(xSocket,'photo'),sPhoto=next(sSocket,'photo');
    const upload=await fetch(origin+'/api/photo',{method:'POST',headers:{'Content-Type':'image/png','X-Photo-Token':item.photoToken},body:png});assert.equal(upload.status,200,await upload.clone().text());
    assert.equal((await xPhoto).id,item.requestId);assert.equal((await sPhoto).id,item.requestId);
    const photo=await fetch(origin+'/api/app/requests/'+item.requestId+'/photo',{headers:appHeaders});assert.equal(photo.status,200);assert.deepEqual(Buffer.from(await photo.arrayBuffer()),png);
    const expiryDb=new DatabaseSync(path.join(dir,'state.sqlite'));expiryDb.prepare('UPDATE photo_records SET expiry=?').run(Date.now()-1);expiryDb.close();
    assert.equal((await fetch(origin+'/api/app/requests/'+item.requestId+'/photo',{headers:appHeaders})).status,404);
    const xConfirmed=next(xSocket,'confirmed'),sConfirmed=next(sSocket,'confirmed');
    const confirmed=await call('/api/app/requests/'+item.requestId+'/confirm',{},appHeaders);assert.equal(confirmed.status,200);
    assert.equal((await xConfirmed).id,item.requestId);assert.equal((await sConfirmed).id,item.requestId);
    const updated=await fetch(origin+'/api/app/requests/'+item.requestId,{headers:{Authorization:`Bearer ${xiaomi.credential}`}});assert.equal((await updated.json()).status,'confirmed');
    sSocket.terminate();await sleep(80);
    const xOnly=next(xSocket,'request');
    const missedResponse=await call('/api/notify',{message:'三星断线期间的新请求'});assert.equal(missedResponse.status,200);
    const missed=await missedResponse.json();assert.equal((await xOnly).id,missed.requestId);
    sSocket=await connect(samsung.credential);
    const recoveredList=await fetch(origin+'/api/app/requests',{headers:appHeaders});
    assert.ok((await recoveredList.json()).items.some(entry=>entry.id===missed.requestId),'reconnected phone can fetch missed request');
    const devices=await fetch(origin+'/api/admin/app-devices',{headers:{Cookie:cookie}});assert.equal((await devices.json()).items.length,2);
    const revokedSocket=new Promise(resolve=>xSocket.once('close',resolve));
    assert.equal((await admin('/api/admin/app-devices/revoke',{id:xiaomi.deviceId})).status,200);
    await revokedSocket;
    assert.equal((await fetch(origin+'/api/app/requests',{headers:{Authorization:`Bearer ${xiaomi.credential}`}})).status,401);
    await assert.rejects(connect(xiaomi.credential),'revoked credential cannot reconnect WebSocket');
    xSocket.terminate();sSocket.terminate();
    await sleep(80);
    const failed=await call('/api/notify',{message:'无人在线'});assert.equal(failed.status,502,'offline delivery must fail when no legacy channel is enabled');
    const recovered=await fetch(origin+'/api/app/requests',{headers:appHeaders});assert.equal(recovered.status,200,'offline device can resynchronize history');
  }finally{server.kill();}
});
